<?php

declare(strict_types=1);

namespace Nowo\StorageKitBundle\Entity;

use DateTimeImmutable;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Component\Uid\Uuid;

use function array_map;
use function array_values;

/**
 * A file uploaded into a text, kept only in an S3-compatible bucket (`profile`). Texts point at it by
 * `<scheme>:<uuid>` (or its download path), never by a bucket URL. The context (`context_type` + `context_id`) decides
 * who reads it; `owner` says who pays for it (usage and limits). `variants` holds the generated preview / thumbnail
 * (key, size, width, height, mime); a missing variant falls back to the original. The object key is random and
 * generated by the server (`yyyy/mm/<uuid>`), never derived from user input.
 *
 * `orphanedSince` is set while no text points at the file (from the upload until a text is saved with it, and again
 * when the last text drops it or its context is deleted); the purge removes orphans older than the retention.
 *
 * @phpstan-type Variant array{key: string, size: int, width: int, height: int, mime: string}
 */
#[ORM\Entity]
#[ORM\Table(name: 'storage_kit_file')]
#[ORM\UniqueConstraint(name: 'uniq_storage_kit_file_uuid', columns: ['uuid'])]
#[ORM\UniqueConstraint(name: 'uniq_storage_kit_file_key', columns: ['profile_id', 'storage_key'])]
#[ORM\Index(name: 'idx_storage_kit_file_context', columns: ['context_type', 'context_id'])]
#[ORM\Index(name: 'idx_storage_kit_file_owner', columns: ['owner'])]
#[ORM\Index(name: 'idx_storage_kit_file_uploader', columns: ['uploaded_by'])]
#[ORM\Index(name: 'idx_storage_kit_file_orphaned', columns: ['orphaned_since'])]
class StoredFile
{
    /** The uploaded image (re-encoded). */
    public const VARIANT_ORIGINAL = 'original';

    /** The large preview. */
    public const VARIANT_PREVIEW = 'preview';

    /** The thumbnail. */
    public const VARIANT_THUMB = 'thumb';

    /** Every variant name (download route requirement). */
    public const VARIANTS = [self::VARIANT_ORIGINAL, self::VARIANT_PREVIEW, self::VARIANT_THUMB];

    /** Name kept after a personal-data erasure. */
    public const ANONYMOUS_NAME = 'image';

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    #[ORM\Column(length: 36)]
    private string $uuid;

    #[ORM\Column(name: 'uploaded_by', length: 180, nullable: true)]
    private ?string $uploadedBy = null;

    #[ORM\Column(length: 64, nullable: true)]
    private ?string $owner = null;

    /** @var array<string, Variant> */
    #[ORM\Column(type: 'json')]
    private array $variants = [];

    /** The original and every variant: what the file costs in the bucket (usage, one SUM). */
    #[ORM\Column(name: 'total_bytes', type: 'bigint')]
    private int|string $totalBytes;

    #[ORM\Column(name: 'created_at')]
    private DateTimeImmutable $createdAt;

    #[ORM\Column(name: 'orphaned_since', nullable: true)]
    private ?DateTimeImmutable $orphanedSince = null;

    /**
     * @param string|null $uuid public id (generated when null)
     */
    public function __construct(
        #[ORM\ManyToOne(targetEntity: StorageProfile::class)]
        #[ORM\JoinColumn(name: 'profile_id', nullable: false)]
        private StorageProfile $profile,
        #[ORM\Column(name: 'context_type', length: 16)]
        private string $contextType,
        #[ORM\Column(name: 'context_id', length: 64)]
        private string $contextId,
        #[ORM\Column(name: 'storage_key', length: 255)]
        private string $storageKey,
        #[ORM\Column(name: 'original_name', length: 255)]
        private string $originalName,
        #[ORM\Column(name: 'mime_type', length: 32)]
        private string $mimeType,
        #[ORM\Column(type: 'bigint')]
        private int|string $size,
        #[ORM\Column]
        private int $width,
        #[ORM\Column]
        private int $height,
        #[ORM\Column(length: 64)]
        private string $sha256,
        ?string $uuid = null,
    ) {
        $this->uuid       = $uuid ?? Uuid::v4()->toRfc4122();
        $this->createdAt  = new DateTimeImmutable();
        $this->totalBytes = $this->getSize();
    }

    /**
     * Database id (move cursor order).
     */
    public function getId(): ?int
    {
        return $this->id;
    }

    /**
     * Public id (URI and download URL).
     */
    public function getUuid(): string
    {
        return $this->uuid;
    }

    /**
     * The bucket holding the objects.
     */
    public function getProfile(): StorageProfile
    {
        return $this->profile;
    }

    /**
     * Context type.
     */
    public function getContextType(): string
    {
        return $this->contextType;
    }

    /**
     * Context id.
     */
    public function getContextId(): string
    {
        return $this->contextId;
    }

    /**
     * Object key of the original (relative to the prefix).
     */
    public function getStorageKey(): string
    {
        return $this->storageKey;
    }

    /**
     * File name given at upload (cleaned; default alt text).
     */
    public function getOriginalName(): string
    {
        return $this->originalName;
    }

    /**
     * Sniffed type of the original.
     */
    public function getMimeType(): string
    {
        return $this->mimeType;
    }

    /**
     * Bytes of the original.
     */
    public function getSize(): int
    {
        return (int) $this->size;
    }

    /**
     * The original and every variant: what the file costs in the bucket.
     */
    public function totalBytes(): int
    {
        return (int) $this->totalBytes;
    }

    /**
     * Width of the original.
     */
    public function getWidth(): int
    {
        return $this->width;
    }

    /**
     * Height of the original.
     */
    public function getHeight(): int
    {
        return $this->height;
    }

    /**
     * SHA-256 of the original (move verification).
     */
    public function getSha256(): string
    {
        return $this->sha256;
    }

    /**
     * User identifier of the uploader (null after an erasure).
     */
    public function getUploadedBy(): ?string
    {
        return $this->uploadedBy;
    }

    /**
     * Sets the uploader.
     */
    public function setUploadedBy(?string $userIdentifier): void
    {
        $this->uploadedBy = $userIdentifier;
    }

    /**
     * Usage owner key.
     */
    public function getOwner(): ?string
    {
        return $this->owner;
    }

    /**
     * Sets the usage owner.
     */
    public function setOwner(?string $owner): void
    {
        $this->owner = $owner;
    }

    /**
     * Adds a generated variant.
     *
     * @param Variant $variant
     */
    public function addVariant(string $name, array $variant): void
    {
        $this->variants[$name] = $variant;
        $this->totalBytes      = $this->totalBytes() + $variant['size'];
    }

    /**
     * Generated variants.
     *
     * @return array<string, Variant>
     */
    public function getVariants(): array
    {
        return $this->variants;
    }

    /**
     * The object key, type and size a variant is served from (the original when the variant was not generated).
     *
     * @return array{key: string, mime: string, width: int, height: int}
     */
    public function variant(string $name): array
    {
        $variant = $this->variants[$name] ?? null;

        return $variant === null
            ? ['key' => $this->storageKey, 'mime' => $this->mimeType, 'width' => $this->width, 'height' => $this->height]
            : ['key' => $variant['key'], 'mime' => $variant['mime'], 'width' => $variant['width'], 'height' => $variant['height']];
    }

    /**
     * Every object key of the file.
     *
     * @return list<string>
     */
    public function objectKeys(): array
    {
        return [$this->storageKey, ...array_values(array_map(static fn (array $v): string => $v['key'], $this->variants))];
    }

    /**
     * Upload time.
     */
    public function getCreatedAt(): DateTimeImmutable
    {
        return $this->createdAt;
    }

    /**
     * Since when no text points at the file (null = referenced).
     */
    public function getOrphanedSince(): ?DateTimeImmutable
    {
        return $this->orphanedSince;
    }

    /**
     * No text points at the file (kept from the first time: the retention window does not restart).
     */
    public function markOrphaned(DateTimeImmutable $since): void
    {
        $this->orphanedSince ??= $since;
    }

    /**
     * An orphan the next purge removes (an erased uploader's files that no text shows).
     */
    public function expireOrphan(DateTimeImmutable $longAgo): void
    {
        $this->orphanedSince = $longAgo;
    }

    /**
     * A personal-data erasure keeps the file of a kept text but not its name (it may name the person) nor the uploader.
     */
    public function anonymise(): void
    {
        $this->originalName = self::ANONYMOUS_NAME;
        $this->uploadedBy   = null;
    }
}
